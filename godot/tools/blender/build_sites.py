# Regenerate the site assets of lane/sites: the Halloway Lake boat launch and the old cabin track and cave.
#   blender -b --factory-startup --python godot/tools/blender/build_sites.py -- [only=name,name] [group=launch|track]
# Writes godot/assets/models/sites/<name>.glb, assets/models/sites/manifest.json and game/site_manifest.gd (sizes, named
# nodes, pivots, triangle counts, LOD distance, metadata and the Blender-side checks, read by game/site_assets.gd and
# test/sites_blender_test.gd). Textures first: python -I tools/blender/make_site_textures.py <godot dir>.
import sys, os, json, time
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import sites_lib as L
import sites_launch, sites_track

args = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
opt = dict(a.split("=", 1) for a in args if "=" in a)
only = set(opt["only"].split(",")) if opt.get("only") else None
groups = {"launch": sites_launch.LAUNCH, "track": sites_track.TRACK}
makers = []
for g, lst in groups.items():
    if opt.get("group") and opt["group"] != g:
        continue
    makers += [(g, m) for m in lst]

man_path = os.path.join(L.OUT, "manifest.json")
manifest = {}
if os.path.exists(man_path):
    with open(man_path) as f:
        manifest = json.load(f)
t0 = time.time()
failed = []
for g, mk in makers:
    asset = mk()
    if only and asset.name not in only:
        continue
    try:
        m = L.build(asset)
    except Exception as e:
        import traceback
        traceback.print_exc()
        failed.append(asset.name)
        continue
    m["group"] = g
    manifest[asset.name] = m
    with open(man_path, "w") as f:
        json.dump(manifest, f, indent=1, sort_keys=True)


def gd(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        return repr(round(v, 4))
    if isinstance(v, str):
        return '"%s"' % v.replace('"', "'")
    if isinstance(v, (list, tuple)):
        if len(v) == 3 and all(isinstance(x, (int, float)) and not isinstance(x, bool) for x in v):
            return "Vector3(%s, %s, %s)" % tuple(gd(float(x)) for x in v)
        return "[" + ", ".join(gd(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{" + ", ".join('"%s": %s' % (k, gd(x)) for k, x in sorted(v.items())) + "}"
    return str(v)


lines = ["class_name SiteManifest", "extends RefCounted",
         "## Generated by tools/blender/build_sites.py. Do not edit: re-run the Blender build instead.",
         "## Per asset: file, group (launch | track), tris [LOD0, LOD1], size (x, y, z metres), aabb_lo/hi (game frame: +z is the",
         "## front, y up, origin at the base), nodes {name: {pivot, rot (degrees), tris, materials}}, lod_end (metres: LOD0 to",
         "## LOD1), meta (waterline, text rectangle, notes), checks (floating parts, inside-out pieces, min_y, probes), buried_ok.", "",
         "const DATA := {"]
for name in sorted(manifest):
    lines.append('\t"%s": %s,' % (name, gd(manifest[name])))
lines.append("}")
with open(os.path.join(L.GODOT, "game", "site_manifest.gd"), "w", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print("DONE %d assets in %.0f s; failed: %s" % (len(manifest), time.time() - t0, failed))
