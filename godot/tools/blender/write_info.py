# Collects tools/blender/info/<name>.json (written by build_animal.py) into game/animal_info.gd, the numbers the game needs.
import json, os, glob

def write(info_dir, out):
    rows = []
    for f in sorted(glob.glob(os.path.join(info_dir, "*.json"))):
        d = json.load(open(f))
        if not isinstance(d, dict) or "name" not in d: continue
        sp = ", ".join('"%s": %s' % (k, v) for k, v in sorted(d.get("clip_speeds", {}).items()))
        tr = ", ".join('"%s": %d' % (k, v) for k, v in sorted(d.get("tris", {}).items()))
        cl = ", ".join('"%s"' % c for c in d.get("clips", []))
        rows.append('\t"%s": {"uv_m": %s, "height": %s, "length": %s, "speeds": {%s}, "clips": [%s], "tris": {%s}, "bytes": %d},'
                    % (d["name"], d.get("uv_m", 3.0), d.get("height", 1.0), d.get("length", 2.0), sp, cl, tr, d.get("bytes", 0)))
    src = ("class_name AnimalInfo\nextends RefCounted\n"
           "## Generated by tools/blender/write_info.py from the animal builds (do not edit by hand): metres of hide per UV unit\n"
           "## (the fur shader's strand layout), standing height and length in metres, the ground speed each moving clip was made for\n"
           "## (m/s: play the clip while the animal moves at about this speed), the clips and the triangles per mesh.\n"
           "const INFO := {\n" + "\n".join(rows) + "\n}\n")
    open(out, "w", newline="\n").write(src)
