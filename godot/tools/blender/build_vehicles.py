# Regenerate the Blender vehicles. Usage (from anywhere):
#   blender -b --factory-startup --python godot/tools/blender/build_vehicles.py -- [only=name,name] [out=dir] [nobake] [render=dir]
# Writes godot/assets/models/vehicles/<name>.glb (LOD0..2 on one armature, actions) and game/vehicle_manifest.gd.
import sys, os, json
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import bpy
import vk_core, vk_body, vk_wheels, vk_details, vk_interior, vk_assemble, vk_rig, vk_build, vk_recipes, vk_render
import vk_recipes_cars, vk_recipes_heavy, vk_recipes_custom, vk_icecream, vk_small
GODOT = os.path.normpath(os.path.join(HERE, "..", ".."))

args = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
opt = {}
for a in args:
    if "=" in a:
        k, v = a.split("=", 1); opt[k] = v
    else:
        opt[a] = True
out_dir = opt.get("out", os.path.join(GODOT, "assets", "models", "vehicles"))
os.makedirs(out_dir, exist_ok=True)
only = opt.get("only", "").split(",") if opt.get("only") else None

man_path = os.path.join(out_dir, "manifest.json")
manifest = {}
if os.path.exists(man_path):
    with open(man_path) as f:
        manifest = json.load(f)

for name, rc in vk_recipes.RECIPES.items():
    if only and name not in only:
        continue
    print("BUILD", name)
    m = vk_build.build(rc, out_dir, bake=not opt.get("nobake"))
    manifest[name] = m
    print("BUILT", name, "tris", m["tris"], "size", m["size"], "checks", m.get("checks"), flush=True)
    with open(man_path, "w") as f:          # keep the manifest current after every vehicle (a later failure loses nothing)
        json.dump(manifest, f, indent=1, sort_keys=True)
    if opt.get("render"):
        rd = opt["render"]
        os.makedirs(rd, exist_ok=True)
        for o in bpy.data.objects:
            if "_LOD1" in o.name or "_LOD2" in o.name:
                o.hide_render = True
        vk_render.setup(samples=int(opt.get("samples", 32)))
        L = m["size"][2]; H = m["size"][1]
        for v in opt.get("views", "front34,side,rear34").split(","):
            vk_render.view(v, L, H)
            vk_render.shot(os.path.join(rd, "%s_%s.png" % (name, v)))

with open(man_path, "w") as f:
    json.dump(manifest, f, indent=1, sort_keys=True)


# the manifest as GDScript (so the game needs no JSON parsing and the export always carries it)
def gd(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(round(v, 4)) if isinstance(v, float) else str(v)
    if isinstance(v, str):
        return '"%s"' % v
    if isinstance(v, (list, tuple)):
        if len(v) == 3 and all(isinstance(x, (int, float)) for x in v):
            return "Vector3(%s, %s, %s)" % tuple(gd(float(x)) for x in v)
        return "[" + ", ".join(gd(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{" + ", ".join('"%s": %s' % (k, gd(x)) for k, x in sorted(v.items())) + "}"
    return str(v)


lines = ["class_name VehicleManifest", "extends RefCounted",
         "## Generated by tools/blender/build_vehicles.py. Do not edit: re-run the Blender build instead.",
         "## Per vehicle: file, tris [LOD0, LOD1, LOD2], size (x, y up, z length) in metres, bones, actions, wheels",
         "## [{bone, pos (game frame: front is -z), radius, steer}], paint and paint2 (sRGB), materials, hinges (opening",
         "## angles, degrees), kind, pose (an action applied when placed), colliders (AABB [lo, hi] in the game frame).", "",
         "const DATA := {"]
for name in sorted(manifest):
    lines.append('\t"%s": %s,' % (name, gd(manifest[name])))
lines.append("}")
with open(os.path.join(GODOT, "game", "vehicle_manifest.gd"), "w", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print("DONE", len(manifest))
