"""Regenerate every lane-osui asset, mock and sheet, then write assets/ui/osui/OSUI-MANIFEST.md.

  python build_osui.py            (about 5 minutes)
  python build_osui.py --fetch    (also re-download the icon sets and fonts first)
Needs Python 3.11 + Pillow + numpy + resvg-py (pip install --use-feature=truststore resvg-py).
HUD mocks need clean background frames in docs/realism/osui/src/ (captured with tools/ui_art/osui/capture_bg.ps1).
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import osui_lib as L


def manifest():
    rows = sorted(set((r[0], r[1], r[2], tuple(r[3]) if r[3] else None, r[4]) for r in L.MANIFEST))
    out = ["# OS UI art manifest (lane osui)", "",
           "Generated by `godot/tools/ui_art/osui/build_osui.py`. PNG unless noted. `<px>`, `<app>`, `<name>` stand for the",
           "size folders and keys listed in the note. 9-patch margins are left, top, right, bottom in pixels of the file.",
           "Spec: `docs/OS-UX-SPEC-2026-10-24.md`.", "",
           "| File | Size | 9-patch | Note |", "|---|---|---|---|"]
    for rel, w, h, nine, note in rows:
        size = f"{w} x {h}" if w else "-"
        out.append(f"| `{rel}` | {size} | {', '.join(map(str, nine)) if nine else '-'} | {note} |")
    p = os.path.join(L.OUT, "OSUI-MANIFEST.md")
    with open(p, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    return len(rows)


if __name__ == "__main__":
    if "--fetch" in sys.argv:
        import fetch_icons; fetch_icons.main()
    import gen_icons, gen_system, gen_components, gen_hud, gen_map, gen_apps, gen_mocks, gen_hud_mocks, gen_sheets
    gen_icons.build(); print("icons")
    gen_system.build(); print("system glyphs")
    gen_components.build(); print("components")
    gen_hud.build(); print("hud")
    gen_map.build(); print("map")
    gen_apps.build(); print("apps")
    print("manifest rows", manifest())
    gen_mocks.build()
    if os.path.exists(os.path.join(L.REAL, "src", "bg_16x9.png")):
        gen_hud_mocks.build()
    gen_sheets.build()
