def save_ui(im, rel, nine=None, note="", quality=None):
    path = os.path.join(UI, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if rel.endswith(".jpg"):
        im.convert("RGB").save(path, quality=quality or 90, optimize=True)
    else:
        im.save(path, optimize=True)
    MANIFEST.append((rel.replace("\\", "/"), im.size[0], im.size[1], nine, note))
    return path


def gcanvas(S, H=None):
    """A canvas whose units are a 24 x 24 glyph grid centred on the image (one unit = S/24 px)."""
    return Canvas(S, H).unit(S / 2, (H or S) / 2, S / 24.0)


def orrect(c, x0, y0, x1, y1, r, w):
    return c.rrect(x0 - w / 2, y0 - w / 2, x1 + w / 2, y1 + w / 2, r + w / 2) - c.rrect(x0 + w / 2, y0 + w / 2, x1 - w / 2, y1 - w / 2, max(0.01, r - w / 2))


def ocircle(c, x, y, r, w):
    return c.ring(x, y, r, w)


def tile_noise(n, seed, octaves=((8, 1.0), (16, 0.5), (32, 0.25), (64, 0.12))):
    """Periodic (tileable) value noise in 0..1 at n x n, built by bicubic upsampling of wrapped random grids."""
    rng = np.random.default_rng(seed)
    acc = np.zeros((n, n), np.float32)
    tot = 0.0
    for cells, amp in octaves:
        g = rng.random((cells, cells)).astype(np.float32)
        big = np.tile(g, (3, 3))
        im = Image.fromarray((big * 255).astype(np.uint8), "L").resize((n * 3, n * 3), Image.BICUBIC)
        a = np.asarray(im, np.float32)[n:2 * n, n:2 * n] / 255.0
        acc += a * amp
        tot += amp
    acc /= tot
    acc = (acc - acc.min()) / max(1e-6, acc.max() - acc.min())
    return acc


def distress(im, seed, amount=0.45, speck=0.10, edge_soft=0.6):
    """Worn ink: knock holes in the alpha with blotchy noise and a few specks, keep it mostly legible."""
    w, h = im.size
    n = max(w, h)
    nz = tile_noise(n, seed, ((6, 1.0), (14, 0.6), (40, 0.35), (110, 0.25)))[:h, :w]
    a = np.asarray(im.getchannel("A"), np.float32) / 255.0
    keep = np.clip((nz - amount * 0.55) / 0.22, 0.0, 1.0)
    keep = 0.35 + 0.65 * keep
    rng = np.random.default_rng(seed + 7)
    sp = rng.random((h, w)) < speck * 0.02
    spm = Image.fromarray((sp * 255).astype(np.uint8), "L").filter(ImageFilter.MaxFilter(3)).filter(ImageFilter.GaussianBlur(edge_soft))
    keep *= 1.0 - np.asarray(spm, np.float32) / 255.0 * 0.9
    out = im.copy()
    out.putalpha(Image.fromarray(np.clip(a * keep * 255, 0, 255).astype(np.uint8), "L"))
    return out


def recolor(im, col):
    """Flat recolour keeping alpha (used for monochrome glyph variants)."""
    out = Image.new("RGBA", im.size, (col[0], col[1], col[2], 0))
    out.putalpha(im.getchannel("A"))
    return out
